type ctxKey struct{}

// New returns a fresh-schema App; register route packages on a.Mux and serve with Server.
func New(t *testing.T) *app.App {
	t.Helper()
	url := os.Getenv("PHOTOLY_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("PHOTOLY_TEST_DATABASE_URL not set")
	}
	pool, err := pgxpool.New(context.Background(), url)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	// Test packages run in parallel against one database: hold a session lock for the whole test.
	lock, err := pool.Acquire(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if _, err := lock.Exec(context.Background(), `SELECT pg_advisory_lock(8675309)`); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_, _ = lock.Exec(context.Background(), `SELECT pg_advisory_unlock(8675309)`)
		lock.Release()
	})
	if _, err := pool.Exec(context.Background(), schema); err != nil {
		t.Fatal(err)
	}
	legacy.Sessions = nil
	if err := legacy.UseDefaultSessions(context.Background(), pool); err != nil {
		t.Fatal(err)
	}
	a := &app.App{Pool: pool, Mux: http.NewServeMux(), Cfg: app.Config{UploadFolder: t.TempDir()}}
	// Stand-in for the skeleton's Auth: HRD-Token header -> session -> user, else the legacy 403 envelope.
	a.Auth = func(h http.HandlerFunc) http.HandlerFunc {
		return func(w http.ResponseWriter, r *http.Request) {
			id, ok := legacy.Sessions.Identify(r.Context(), r.Header.Get("HRD-Token"))
			if !ok {
				w.Header().Set("Content-Type", "application/json")
				_, _ = w.Write([]byte(`{"t":null,"msgCode":403}`))
				return
			}
			h(w, r.WithContext(context.WithValue(r.Context(), ctxKey{}, id)))
		}
	}
	a.UserFrom = func(ctx context.Context) app.User { return app.User{ID: ctx.Value(ctxKey{}).(int64)} }
	return a
}

// Client calls the mux and decodes JSON responses.
type Client struct {
	T     *testing.T
	Mux   http.Handler
	Token string
}

func (c *Client) Do(method, path, ctype string, body io.Reader) (int, []byte) {
	req := httptest.NewRequest(method, path, body)
	if ctype != "" {
		req.Header.Set("Content-Type", ctype)
	}
	if c.Token != "" {
		req.Header.Set("HRD-Token", c.Token)
	}
	rec := httptest.NewRecorder()
	c.Mux.ServeHTTP(rec, req)
	return rec.Code, rec.Body.Bytes()
}

// JSON posts v as JSON (nil for GET/no body) and returns the decoded object.
func (c *Client) JSON(method, path string, v any) map[string]any {
	c.T.Helper()
	var body io.Reader
	if v != nil {
		b, _ := json.Marshal(v)
		body = bytes.NewReader(b)
	}
	_, raw := c.Do(method, path, "application/json", body)
	var out map[string]any
	if err := json.Unmarshal(raw, &out); err != nil {
		c.T.Fatalf("%s %s: not a JSON object: %q", method, path, raw)
	}
	return out
}

// Want asserts msgCode and returns t.
func (c *Client) Want(m map[string]any, code float64) any {
	c.T.Helper()
	if m["msgCode"] != code {
		c.T.Fatalf("msgCode = %v, want %v (%v)", m["msgCode"], code, m)
	}
	return m["t"]
}
