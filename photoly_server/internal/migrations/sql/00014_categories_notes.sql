CREATE FUNCTION classification_content_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO media_classification(photo_id,content_version) VALUES(NEW.photo_id,NEW.content_version)
 ON CONFLICT(photo_id) DO UPDATE SET content_version=NEW.content_version,categories='{}',state='pending',attempts=0,next_attempt=now(),lease_token=NULL,error=NULL;
 RETURN NEW;
END $$;
-- +goose StatementEnd
CREATE TRIGGER classification_insert AFTER INSERT ON photo FOR EACH ROW EXECUTE FUNCTION classification_content_changed();
CREATE TRIGGER classification_replace AFTER UPDATE OF content_version ON photo FOR EACH ROW WHEN (OLD.content_version IS DISTINCT FROM NEW.content_version) EXECUTE FUNCTION classification_content_changed();
CREATE VIEW effective_media_category AS
 SELECT p.photo_id,p.user_id,'video'::text AS category FROM photo p WHERE lower(p.format) IN ('mp4','avi','wmv','mpeg','m4v','mov','flv','asf','f4v','rmvb','vob','rm')
 UNION ALL SELECT p.photo_id,p.user_id,'live' FROM photo p JOIN photo_media m USING(photo_id) WHERE m.live
 UNION ALL SELECT p.photo_id,p.user_id,'animated' FROM photo p JOIN photo_media m USING(photo_id) WHERE m.animated AND NOT m.live
 UNION ALL SELECT p.photo_id,p.user_id,c.category FROM photo p CROSS JOIN (VALUES ('panorama'),('screenshot'),('portrait')) AS c(category)
 LEFT JOIN media_classification a ON a.photo_id=p.photo_id AND a.content_version=p.content_version
 LEFT JOIN media_category_override o ON o.photo_id=p.photo_id AND o.category=c.category
 WHERE coalesce(o.included,c.category=ANY(a.categories),false);
