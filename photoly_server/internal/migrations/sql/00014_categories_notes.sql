CREATE TABLE media_classification (
 photo_id integer PRIMARY KEY REFERENCES photo(photo_id) ON DELETE CASCADE,
 content_version integer NOT NULL, rule_version integer NOT NULL DEFAULT 1,
 categories text[] NOT NULL DEFAULT '{}', state text NOT NULL DEFAULT 'pending',
 attempts integer NOT NULL DEFAULT 0, next_attempt timestamptz NOT NULL DEFAULT now(),
 lease_token text, error text
);
CREATE INDEX media_classification_work ON media_classification(next_attempt,photo_id) WHERE state<>'ready';
CREATE TABLE media_category_override (
 photo_id integer NOT NULL REFERENCES photo(photo_id) ON DELETE CASCADE,
 category text NOT NULL CHECK(category IN ('panorama','screenshot','portrait')),
 included boolean NOT NULL, PRIMARY KEY(photo_id,category)
);
CREATE TABLE media_note (
 note_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 photo_id integer NOT NULL REFERENCES photo(photo_id) ON DELETE CASCADE,
 user_id integer NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
 body text NOT NULL CHECK(length(body) BETWEEN 1 AND 100000),
 x double precision, y double precision, content_version integer,
 revision integer NOT NULL DEFAULT 1,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((x IS NULL AND y IS NULL AND content_version IS NULL) OR
 (x IS NOT NULL AND y IS NOT NULL AND content_version IS NOT NULL AND x BETWEEN 0 AND 1 AND y BETWEEN 0 AND 1))
);
CREATE INDEX media_note_owner_photo ON media_note(user_id,photo_id,note_id);
